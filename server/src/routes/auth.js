const router = require("express").Router();
const rateLimit = require("express-rate-limit");
const { signup, signin, me, csrf, logout } = require("../controllers/auth");
const { validate } = require("../middleware/validate");
const { signupSchema, signinSchema } = require("../validators/schemas");
const { requireAuth } = require("../middleware/auth");
const loginLimiter = rateLimit({ windowMs: 15*60*1000, limit: 10, standardHeaders: true, legacyHeaders: false });
router.get("/csrf", csrf);
router.post("/signup", loginLimiter, validate(signupSchema), signup);
router.post("/signin", loginLimiter, validate(signinSchema), signin);
router.get("/me", me);
router.post("/logout", requireAuth, logout);
module.exports = router;
